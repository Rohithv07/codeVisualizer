package com.visualizer.runner;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.visualizer.model.TraceRequest;
import com.visualizer.model.TraceResponse;
import org.springframework.stereotype.Component;

import java.io.File;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.HashMap;
import java.util.Map;
import java.util.concurrent.TimeUnit;

@Component
public class CppTraceRunner implements LanguageRunner {

    private final ObjectMapper objectMapper = new ObjectMapper();

    @Override
    public boolean supports(String language) {
        if (language == null) return false;
        String lang = language.trim().toLowerCase();
        return "cpp".equals(lang) || "c++".equals(lang) || "c".equals(lang);
    }

    @Override
    public TraceResponse run(TraceRequest request) throws Exception {
        File tracerScript = findTracerScript();
        if (!tracerScript.exists()) {
            return TraceResponse.error("SERVER_ERROR", "cpp",
                    "C++ tracer script not found at: " + tracerScript.getAbsolutePath());
        }

        File outFile = File.createTempFile("cpp_trace_out_", ".json");
        File errFile = File.createTempFile("cpp_trace_err_", ".log");

        try {
            String pythonCmd = "python3";
            if (new File("/usr/bin/python3").exists()) {
                pythonCmd = "/usr/bin/python3";
            }
            ProcessBuilder pb = new ProcessBuilder(pythonCmd, tracerScript.getAbsolutePath(), "--cli");
            pb.redirectOutput(outFile);
            pb.redirectError(errFile);

            Process process = pb.start();

            // Write input payload
            Map<String, Object> payload = new HashMap<>();
            payload.put("code", request.code() != null ? request.code() : "");
            payload.put("input", request.input() != null ? request.input() : "");
            payload.put("maxSteps", request.maxSteps());

            try (OutputStream os = process.getOutputStream()) {
                objectMapper.writeValue(os, payload);
                os.flush();
            }

            boolean finishedInTime = process.waitFor(15, TimeUnit.SECONDS);
            if (!finishedInTime) {
                process.destroyForcibly();
                return TraceResponse.error("TIMEOUT", "cpp", "Execution timed out after 15 seconds.");
            }

            int exitCode = process.exitValue();
            if (exitCode != 0) {
                String errorOutput = Files.exists(errFile.toPath()) ? Files.readString(errFile.toPath(), StandardCharsets.UTF_8) : "";
                return TraceResponse.error("RUNTIME_ERROR", "cpp",
                        errorOutput.isEmpty() ? "Process failed with exit code " + exitCode : errorOutput);
            }

            if (!outFile.exists() || outFile.length() == 0) {
                return TraceResponse.error("EMPTY_OUTPUT", "cpp", "No output generated by C++ tracer.");
            }

            return objectMapper.readValue(outFile, TraceResponse.class);

        } finally {
            outFile.delete();
            errFile.delete();
        }
    }

    private File findTracerScript() {
        File f1 = new File("runners/cpp/tracer.py");
        if (f1.exists()) return f1;
        File f2 = new File("../runners/cpp/tracer.py");
        if (f2.exists()) return f2;
        return new File(System.getProperty("user.dir"), "runners/cpp/tracer.py");
    }
}
